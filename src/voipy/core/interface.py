from collections.abc import AsyncIterator
from typing import Protocol

from .audio import AudioFrame
from .events import CallEvent, ProviderEvent


class MediaTransport(Protocol):
    def receive(self) -> AsyncIterator[AudioFrame]: ...
    async def send(self, frame: AudioFrame) -> None: ...
    async def clear(self) -> None: ...
    async def close(self) -> None: ...


class VoiceProvider(Protocol):
    async def connect(self) -> None: ...
    async def send_audio(self, frame: AudioFrame) -> None: ...
    def events(self) -> AsyncIterator[ProviderEvent]: ...
    async def close(self) -> None: ...


class TelephonyAdapter(Protocol):
    async def connect(self) -> None: ...
    def events(self) -> AsyncIterator[CallEvent]: ...
    async def answer(self, channel_id: str) -> None: ...
    async def hangup(self, channel_id: str) -> None: ...
    async def transfer(self, channel_id: str, destination: str) -> None: ...
    async def open_media(self, channel_id: str) -> MediaTransport: ...
    async def close(self) -> None: ...
